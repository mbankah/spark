// Builds the UoB venue directory from OpenStreetMap (L4, L5).
// Run from the efa folder: node tools/gen-venues.mjs
// Reads every venue named on the timetable (core/.../WeekB.kt), asks the Overpass API for the building with that name on
// the Edgbaston campus, writes core/.../Venues.kt and docs/VENUES_REPORT.md. A venue that cannot be matched is listed
// as UNMATCHED in both: the app then asks Michael to place that one venue on a map (L5).
import fs from 'node:fs';

const week = fs.readFileSync('core/src/main/kotlin/efa/WeekB.kt', 'utf8');
const venues = [...new Set([...week.matchAll(/PatternSlot\(DayOfWeek\.\w+, \d+, \d+, "(?:[^"\\]|\\.)*", "(?:lecture|tutorial)", "([^"]+)"/g)].map(m => m[1]))].sort();

// Timetable venue text starts with the building as people say it; map that to the name OpenStreetMap uses.
const rules = [
  ['Murray Learning Centre', 'Murray Learning Centre'],
  ['Watson', 'Watson Building'],
  ['Physics West', 'Physics West'],
  ['Winifred Hackett', 'Winifred Hackett Building'],
  ['Haworth', 'Haworth Building'],
  ['Arts', 'Arts Building'],
  ['Education', 'Education Building'],
];

const names = [...new Set(rules.map(r => r[1]))];
const q = `[out:json][timeout:60];(${names.map(n => `way["name"="${n}"]["building"](52.43,-1.96,52.47,-1.90);`).join('')});out center tags;`;
let res;
for (const [i, url] of ['https://overpass-api.de/api/interpreter', 'https://overpass.kumi.systems/api/interpreter', 'https://overpass-api.de/api/interpreter'].entries()) {
  res = await fetch(url, { method: 'POST', body: new URLSearchParams({ data: q }), headers: { 'User-Agent': 'efa-build/0.1 (personal project; contact mikeybankah@gmail.com)' }, signal: AbortSignal.timeout(45000) }).catch(e => ({ ok: false, status: String(e.name) }));
  if (res.ok) break;
  console.error('Overpass', url, res.status, '(retrying)');
  await new Promise(r => setTimeout(r, 4000 * (i + 1)));
}
if (!res.ok) { console.error('Overpass failed', res.status); process.exit(1); }
const osm = (await res.json()).elements;
const byName = new Map();
for (const e of osm) if (!byName.has(e.tags.name)) byName.set(e.tags.name, e);

const buildings = [], unmatched = [], rows = [];
for (const v of venues) {
  const rule = rules.find(r => v.startsWith(r[0]));
  if (!rule) { unmatched.push(v); rows.push(`| ${v} | no rule for this building name | UNMATCHED | |`); continue; }
  const e = byName.get(rule[1]);
  if (!e) { unmatched.push(v); rows.push(`| ${v} | ${rule[1]} | UNMATCHED: not in OpenStreetMap | |`); continue; }
  if (!buildings.some(b => b.alias === rule[0])) buildings.push({ alias: rule[0], osmName: rule[1], osmId: e.id, lat: e.center.lat, lon: e.center.lon });
  const note = v.includes('Vaughan Jeffreys') ? 'Matched to the Education Building as a whole; the room name Vaughan Jeffreys is not a separate OSM feature, so confirm the building is right.' : '';
  rows.push(`| ${v} | ${rule[1]} (way ${e.id}) | matched | ${note} |`);
}

const f = n => n.toFixed(6);
let kt = `package efa

// GENERATED by tools/gen-venues.mjs from OpenStreetMap on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Data: OpenStreetMap contributors, ODbL. Building centres, not entrances.

data class Building(val alias: String, val osmName: String, val osmWayId: Long, val lat: Double, val lon: Double)

object Venues {
    /** Timetable venue text starts with the alias. */
    val buildings: List<Building> = listOf(
${buildings.map(b => `        Building(${JSON.stringify(b.alias)}, ${JSON.stringify(b.osmName)}, ${b.osmId}L, ${f(b.lat)}, ${f(b.lon)}),`).join('\n')}
    )

    /** Timetable venues the build could not match (L5). The app asks about each of these. */
    val unmatched: List<String> = listOf(${unmatched.map(u => JSON.stringify(u)).join(', ')})

    fun find(venueText: String): Building? = buildings.firstOrNull { venueText.startsWith(it.alias) }
}
`;
fs.writeFileSync('core/src/main/kotlin/efa/Venues.kt', kt);
fs.writeFileSync('docs/VENUES_REPORT.md', `# Venue directory report (L4, L5)

Built ${new Date().toISOString().slice(0, 10)} from OpenStreetMap (ODbL) by \`tools/gen-venues.mjs\`. Every lecture and tutorial venue on the week B timetable was checked.

| Timetable venue | OpenStreetMap match | Result | Note |
|---|---|---|---|
${rows.join('\n')}

Unmatched: ${unmatched.length ? unmatched.join('; ') : 'none'}.

Building centres are used, not entrances, so the 150 m check is measured from the middle of the building. Large buildings may need a wider radius on a real phone; see docs/DEVICE_TESTS.md.
`);
console.log(venues.length, 'venues;', buildings.length, 'buildings;', unmatched.length, 'unmatched');
